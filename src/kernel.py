def _kaggle(*args: str) -> subprocess.CompletedProcess:
    return subprocess.run(
        [sys.executable, "-m", "kaggle", *args], capture_output=True, text=True
    )


def _username() -> str:
    """The account name, taken from whatever credential form is configured."""
    from kaggle.api.kaggle_api_extended import KaggleApi

    api = KaggleApi()
    api.authenticate()
    name = (getattr(api, "config_values", {}) or {}).get("username")
    if name:
        return name
    # Access-token auth does not expose the username locally, so ask the API.
    r = _kaggle("config", "view")
    for line in r.stdout.splitlines():
        if "username" in line.lower():
            return line.split(":")[-1].strip()
    raise SystemExit("could not determine the Kaggle username")


def stage_dataset(staging: Path, user: str, cfg) -> Path:
    """Zip src/ and conf/ into a staging dir with dataset metadata.

    A single zip at the dataset root, because Kaggle datasets flatten directories
    and a package needs its tree intact. `src/metrics.py` is excluded on purpose:
    it imports tracksdata, which is not installed on Kaggle, and nothing in the
    inference path should be able to reach it.
    """
    if staging.exists():
        shutil.rmtree(staging)
    staging.mkdir(parents=True)

    with zipfile.ZipFile(
        staging / ARCHIVE_NAME, "w", zipfile.ZIP_DEFLATED
    ) as zf:
        for name in sorted(os.listdir(REPO_ROOT / "src")):
            if name.endswith(".py") and name != "metrics.py":
                zf.write(REPO_ROOT / "src" / name, f"src/{name}")
        for name in sorted(os.listdir(REPO_ROOT / "conf")):
            if name.endswith((".yaml", ".yml")):
                zf.write(REPO_ROOT / "conf" / name, f"conf/{name}")
        # The leave-one-embryo-out splits, needed by a training kernel. Without
        # this file the reference trainer silently falls back to its seeded
        # 90/10 shuffle over all 199 videos, which puts crops of the same embryo
        # on both sides and is the exact measurement the retrain exists to
        # avoid. A missing file must therefore be loud, and it is checked for in
        # the training template rather than left to fail quietly here.
        for split_name in ("dataset_splits.json", "leak_splits.json"):
            splits = REPO_ROOT / "data" / "meta" / split_name
            if splits.exists():
                zf.write(splits, f"meta/{split_name}")

    (staging / "dataset-metadata.json").write_text(
        json.dumps(
            {
                "title": DATASET_SLUG,
                "id": f"{user}/{DATASET_SLUG}",
                "licenses": [{"name": "CC0-1.0"}],
            },
            indent=2,
        ),
        encoding="utf-8",
    )
    return staging


def push_dataset(staging: Path, user: str, message: str) -> None:
    exists = _kaggle("datasets", "status", f"{user}/{DATASET_SLUG}").returncode == 0
    if exists:
        print(f"updating dataset {user}/{DATASET_SLUG}")
        r = _kaggle("datasets", "version", "-p", str(staging), "-m", message)
    else:
        print(f"creating dataset {user}/{DATASET_SLUG}")
        r = _kaggle("datasets", "create", "-p", str(staging))
    print((r.stdout or r.stderr).strip())
    if r.returncode != 0:
        raise SystemExit("dataset push failed")


def _is_unet(cfg) -> bool:
    """A learned-detector config needs a GPU, the pack, and its wheels."""
    return str((cfg.detect or {}).get("backend", "localmax")) == "unet"


def push_kernel(staging: Path, user: str, cfg, competition: str,
                tag: str = "") -> str:
    """Push the inference kernel, optionally under a suffixed slug.

    One fixed slug means a second config overwrites the first, so measuring three
    arms costs three sequential runs plus three waits. A suffix lets them run at
    once, which matters because a code competition scores the rerun rather than
    the notebook and the turnaround is hours. The suffix is part of the slug, so
    each arm keeps its own version history and its own logs.
    """
    slug = f"{KERNEL_SLUG}-{tag}" if tag else KERNEL_SLUG
    kdir = staging.parent / ("kernel-" + tag if tag else "kernel")
    if kdir.exists():
        shutil.rmtree(kdir)
    kdir.mkdir(parents=True)

    (kdir / "inference.py").write_text(
        NOTEBOOK_TEMPLATE.format(
            competition=competition,
            config_name=cfg.name,
            config_hash=cfg.hash(),
            config_file=Path(cfg.path).name,
            dataset_slug=DATASET_SLUG,
            archive=ARCHIVE_NAME,
            user=user,
            pack_slug=PACK_SLUG,
            prelude=UNET_PRELUDE if _is_unet(cfg) else "",
        ),
        encoding="utf-8",
    )
    (kdir / "kernel-metadata.json").write_text(
        json.dumps(
            {
                "id": f"{user}/{slug}",
                "title": slug,
                "code_file": "inference.py",
                "language": "python",
                "kernel_type": "script",
                "is_private": True,
                "enable_gpu": _is_unet(cfg),
                "enable_tpu": False,
                # Must stay false: the rerun disables internet, and a kernel that
                # only works with it on will fail exactly when it matters.
                "enable_internet": False,
                "competition_sources": [competition],
                "dataset_sources": (
                    [f"{user}/{DATASET_SLUG}"]
                    + ([PACK_SLUG] if _is_unet(cfg) else [])
                ),
                "kernel_sources": [],
                "model_sources": [],
            },
            indent=2,
        ),
        encoding="utf-8",
    )

    # `enable_gpu` alone gets a P100, and this competition refuses to accept a
    # submission from a P100 notebook ("Your Notebook cannot use P100 GPUs in
    # this competition"). The accelerator is not a metadata field, so it has to
    # be passed on the push. Valid values: NvidiaTeslaT4, NvidiaTeslaP100,
    # Tpu1VmV38.
    push_args = ["kernels", "push", "-p", str(kdir)]
    if _is_unet(cfg):
        push_args += ["--accelerator", "NvidiaTeslaT4"]
    r = _kaggle(*push_args)
    out = (r.stdout or "") + (r.stderr or "")
    print(out.strip())
    # The CLI exits 0 on a refused push and reports the reason on stdout, so
    # the return code alone is not enough. This was found on 2026-08-28, when
    # "Maximum batch GPU session count of 2 reached" was printed and the pusher
    # then went on to print a notebook URL for a kernel that did not exist.
    # A push that failed must look like a failure.
    if r.returncode != 0 or "error" in out.lower():
        raise SystemExit(f"kernel push failed: {out.strip() or 'no output'}")
    return f"https://www.kaggle.com/code/{user}/{slug}"



