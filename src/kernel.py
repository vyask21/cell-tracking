def push_cache_kernel(staging: Path, user: str, competition: str,
                      det_threshold: float, views: int, gate_um: float,
                      edge_threshold: float, pool_kernel_um: float,
                      tag: str = "") -> str:
    """Push the GPU kernel that builds a screening cache.

    Separate from `push_kernel` because it produces an artifact rather than a
    submission: there is no CSV, nothing to submit to the competition, and the
    output is downloaded with `kaggle kernels output` and dropped into
    `data/meta/`. It still needs the pack, the wheels and a T4, so it reuses the
    same prelude and the same accelerator argument.
    """
    slug = f"{CACHE_SLUG}-{tag}" if tag else CACHE_SLUG
    kdir = staging.parent / ("cache-" + tag if tag else "cache")
    if kdir.exists():
        shutil.rmtree(kdir)
    kdir.mkdir(parents=True)

    from src.graphcache import HELDOUT

    (kdir / "build_cache.py").write_text(
        CACHE_TEMPLATE.format(
            competition=competition,
            dataset_slug=DATASET_SLUG,
            user=user,
            pack_slug=PACK_SLUG,
            prelude=UNET_PRELUDE,
            n_samples=len(HELDOUT),
            det_threshold=det_threshold,
            det_tta=bool(views and views > 1),
            views=int(views),
            gate_um=gate_um,
            edge_threshold=edge_threshold,
            pool_kernel_um=pool_kernel_um,
        ),
        encoding="utf-8",
    )
    (kdir / "kernel-metadata.json").write_text(
        json.dumps(
            {
                "id": f"{user}/{slug}",
                "title": slug,
                "code_file": "build_cache.py",
                "language": "python",
                "kernel_type": "script",
                "is_private": True,
                "enable_gpu": True,
                "enable_tpu": False,
                "enable_internet": False,
                "competition_sources": [competition],
                "dataset_sources": [f"{user}/{DATASET_SLUG}", PACK_SLUG],
                "kernel_sources": [],
                "model_sources": [],
            },
            indent=2,
        ),
        encoding="utf-8",
    )

    r = _kaggle("kernels", "push", "-p", str(kdir),
                "--accelerator", "NvidiaTeslaT4")
    out = (r.stdout or "") + (r.stderr or "")
    print(out.strip())
    if r.returncode != 0 or "error" in out.lower():
        raise SystemExit(f"cache kernel push failed: {out.strip() or 'no output'}")
    return f"https://www.kaggle.com/code/{user}/{slug}"


