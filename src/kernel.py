def push_train_kernel(staging, user, competition, split, epochs, batch_size,
                      max_iters, splits_name="dataset_splits.json",
                      require_disjoint=True, tag="f"):
    """Push a training kernel for one fold of one splits file."""
    kdir = staging.parent / "train_kernel"
    if kdir.exists():
        shutil.rmtree(kdir)
    kdir.mkdir(parents=True)

    max_iters_arg = (
        f'["--max-iters", "{max_iters}"]' if max_iters else "[]"
    )
    slug = f"{TRAIN_SLUG}-{tag}{split}"
    (kdir / "train.py").write_text(
        TRAIN_TEMPLATE.format(
            competition=competition,
            pack_slug=PACK_SLUG,
            split=split,
            epochs=epochs,
            batch_size=batch_size,
            max_iters_arg=max_iters_arg,
            splits_name=splits_name,
            require_disjoint=bool(require_disjoint),
        ),
        encoding="utf-8",
    )
    (kdir / "kernel-metadata.json").write_text(
        json.dumps(
            {
                "id": f"{user}/{slug}",
                "title": slug,
                "code_file": "train.py",
                "language": "python",
                "kernel_type": "script",
                "is_private": True,
                "enable_gpu": True,
                "enable_tpu": False,
                "enable_internet": False,
                "competition_sources": [competition],
                "dataset_sources": [f"{user}/{DATASET_SLUG}", PACK_SLUG],
                "kernel_sources": [],
                "model_sources": [],
            },
            indent=2,
        ),
        encoding="utf-8",
    )
    r = _kaggle("kernels", "push", "-p", str(kdir),
                "--accelerator", "NvidiaTeslaT4")
    print((r.stdout or r.stderr).strip())
    if r.returncode != 0:
        raise SystemExit("training kernel push failed")
    return f"https://www.kaggle.com/code/{user}/{slug}"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("action", choices=["push", "train", "cache"])
    ap.add_argument("--config", default="")
    ap.add_argument("--message", default="update inference code")
    ap.add_argument("--split", type=int, default=0,
                    help="leave-one-embryo-out fold: 0 holds out 44b6, 1 holds out 6bba")
    ap.add_argument("--epochs", type=int, default=1)
    ap.add_argument("--batch-size", type=int, default=8)
    ap.add_argument("--splits-name", default="dataset_splits.json",
                    help="which splits file in the code dataset to train against")
    ap.add_argument("--allow-shared-embryo", action="store_true",
                    help="permit a fold whose train and test share an embryo. "
                         "Only for the matched leak measurement, where sharing "
                         "is the variable under test")
    ap.add_argument("--tag", default="f",
                    help="training kernel slug suffix, so runs do not overwrite "
                         "each other")
    ap.add_argument("--kernel-tag", default="",
                    help="inference kernel slug suffix, so several arms can run "
                         "at once. Empty keeps the original slug, which is what "
                         "every submission before 2026-08-27 used")
    ap.add_argument("--det-threshold", type=float, default=0.99,
                    help="cache action: detection threshold. Must match the "
                         "cache it will be compared against, since the edge "
                         "head's softmax normalises over the nodes present and "
                         "the threshold is therefore a cache key")
    ap.add_argument("--views", type=int, default=8, choices=(1, 4, 8),
                    help="cache action: size of the dihedral TTA group. 1 is no "
                         "TTA at all")
    ap.add_argument("--gate-um", type=float, default=20.0,
                    help="cache action: candidate gate. Wide on purpose so every "
                         "narrower arm can share one cache")
    ap.add_argument("--edge-threshold", type=float, default=0.05)
    ap.add_argument("--pool-kernel-um", type=float, default=5.0)
    ap.add_argument("--max-iters", type=int, default=0,
                    help="cap iterations per epoch; use a small value to "
                         "calibrate throughput before spending real GPU hours")
    a = ap.parse_args()

    competition_ = json.loads(
        (REPO_ROOT / "competition.json").read_text(encoding="utf-8")
    )["slug"]
    if a.action == "cache":
        user = _username()
        staging = Path(REPO_ROOT) / "artifacts" / "kaggle" / "dataset"
        stage_dataset(staging, user, None)
        push_dataset(staging, user, a.message)
        url = push_cache_kernel(
            staging, user, competition_, a.det_threshold, a.views,
            a.gate_um, a.edge_threshold, a.pool_kernel_um, tag=a.kernel_tag,
        )
